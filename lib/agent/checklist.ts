const cache = new Map<string, { items: string[]; source: 'llm' | 'template' }>();

export function templateChecklist(category: string | null): string[] {
  if (!category) return GENERIC;
  return TEMPLATES.find(([re]) => re.test(category))?.[1] ?? GENERIC;
}

/** 5–7 Persian in-person checks for a category; fast model when available, cached per category. */
export async function purchaseChecklist(category: string | null, productTitle: string): Promise<{ items: string[]; source: 'llm' | 'template' }> {
  const key = category ?? 'generic';
  const hit = cache.get(key);
  if (hit) return hit;
  let result: { items: string[]; source: 'llm' | 'template' } = { items: templateChecklist(category), source: 'template' };
  if (llmConfigured()) {
    try {
      const { output } = await generateText({
        model: model('fast'),
        output: Output.object({ schema: z.object({ items: z.array(z.string().max(120)).min(5).max(7) }) }),
        timeout: 6000,
        maxRetries: 0,
        prompt: `برای خرید حضوری «${productTitle}» (دسته «${category ?? 'عمومی'}») در بازار تهران، ۵ تا ۷ نکته کوتاه و عملی فارسی بنویس که خریدار باید داخل مغازه چک کند (اصالت، رجیستری اگر لازم است، پلمب، سریال گارانتی، تست عملکرد، فاکتور). بدون قیمت و بدون نام فروشگاه.`,
      });
      result = { items: output.items, source: 'llm' };
    } catch {
      // keep the template
    }
  }
  cache.set(key, result);
  return result;
}
