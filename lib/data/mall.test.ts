describe('parseMall', () => {
  it.each(CASES)('%s', (address, mall, floor, unit) => {
    const r = parseMall(address);
    expect(r.mall_key).toBe(mall);
    expect(r.floor_num).toBe(floor);
    expect(r.unit_label).toBe(unit);
  });

  it('prefers واحد over پلاک and keeps the kind', () => {
    const r = parseMall('خیابان جمهوری اسلامی، نبش خیابان شیخ هادی، پاساژ علاالدین ۲، طبقه ۲، پلاک ۲۲۳، واحد ۲۲۴');
    expect(r.unit_label).toBe('224');
    expect(r.unit_kind).toBe('واحد');
  });

  it('builds a display name from token + canonical key', () => {
    expect(parseMall('خیابان جمهوری، پاساژ علاالدین، طبقه 6، واحد 656').mall_name).toBe('پاساژ علاءالدین');
  });

  it('returns empty info for empty input', () => {
    expect(parseMall(null).mall_key).toBeNull();
  });
});

describe('parseFloor', () => {
  it.each([
    ['همکف', 0],
    ['منفی یک', -1],
    ['منفی ۱', -1],
    ['-۱', -1],
    ['۱-', -1],
    ['زیرزمین', -1],
    ['اول', 1],
    ['۲', 2],
    ['سوم', 3],
    ['3A', 3],
    ['منفی دو', -2],
    ['آخر', null],
  ] as const)('%s → %s', (label, n) => {
    expect(parseFloor(label)).toBe(n);
  });
});

describe('floorText', () => {
  it('formats floors in Persian', () => {
    expect(floorText(0)).toBe('همکف');
    expect(floorText(6)).toBe('طبقه ۶');
    expect(floorText(-1)).toBe('طبقه منفی ۱');
    expect(floorText(null, null)).toBeNull();
  });
});
